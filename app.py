"""Streamlit dashboard for customer segmentation results."""

from io import BytesIO
from pathlib import Path

import pandas as pd
import streamlit as st


PROJECT_ROOT = Path(__file__).resolve().parent
DEFAULT_RESULTS_PATH = PROJECT_ROOT / "outputs" / "customer_clusters.csv"
REQUIRED_COLUMNS = [
    "CustomerID",
    "RecencyDays",
    "Frequency",
    "Monetary",
    "Cluster",
]
FEATURE_COLUMNS = ["RecencyDays", "Frequency", "Monetary"]


@st.cache_data(show_spinner=False)
def load_results(file_bytes: bytes) -> pd.DataFrame:
    """Load and validate customer-level cluster predictions.

    Args:
        file_bytes: Contents of a CSV file produced by model inference.

    Returns:
        A validated customer-level prediction table.

    Raises:
        ValueError: If required columns are missing or there are no valid rows.
    """
    results = pd.read_csv(BytesIO(file_bytes))
    missing_columns = [column for column in REQUIRED_COLUMNS if column not in results]
    if missing_columns:
        raise ValueError(f"CSV is missing required columns: {', '.join(missing_columns)}")

    results = results[REQUIRED_COLUMNS].copy()
    for column in REQUIRED_COLUMNS:
        results[column] = pd.to_numeric(results[column], errors="coerce")
    results = results.dropna(subset=REQUIRED_COLUMNS)

    if results.empty:
        raise ValueError("The CSV contains no valid customer predictions.")

    for column in ["CustomerID", "Frequency", "Cluster"]:
        if not results[column].mod(1).eq(0).all():
            raise ValueError(f"Column '{column}' must contain whole numbers.")

    results["CustomerID"] = results["CustomerID"].astype("int64")
    results["Cluster"] = results["Cluster"].astype("int64")
    if (results[FEATURE_COLUMNS] < 0).any().any():
        raise ValueError("Feature values must be non-negative.")
    if results["CustomerID"].duplicated().any():
        raise ValueError("Each customer must appear only once in the predictions CSV.")

    return results


def main() -> None:
    """Render the customer segmentation results dashboard."""
    st.set_page_config(
        page_title="Customer Segmentation Dashboard",
        page_icon="🛍️",
        layout="wide",
    )
    st.title("Customer Segmentation Dashboard")
    st.caption("Explore K-Means clusters and customer purchasing patterns.")

    uploaded_file = st.sidebar.file_uploader(
        "Upload predictions CSV",
        type=["csv"],
        help="Use the customer-level CSV generated by `src.inference`.",
    )

    if uploaded_file is not None:
        file_bytes = uploaded_file.getvalue()
        source_label = uploaded_file.name
    elif DEFAULT_RESULTS_PATH.is_file():
        file_bytes = DEFAULT_RESULTS_PATH.read_bytes()
        source_label = str(DEFAULT_RESULTS_PATH.relative_to(PROJECT_ROOT))
    else:
        st.info(
            "No predictions file was found. Run `python -m src.inference` "
            "or upload a customer predictions CSV in the sidebar."
        )
        st.stop()

    try:
        results = load_results(file_bytes)
    except (ValueError, pd.errors.ParserError, UnicodeDecodeError) as error:
        st.error(f"Could not load predictions: {error}")
        st.stop()

    st.caption(f"Data source: `{source_label}`")

    cluster_values = sorted(results["Cluster"].unique().tolist())
    selected_cluster = st.sidebar.selectbox(
        "Cluster",
        options=["All clusters", *cluster_values],
    )
    customer_search = st.sidebar.text_input("Customer ID", placeholder="Search by ID")

    filtered_results = results
    if selected_cluster != "All clusters":
        filtered_results = filtered_results.loc[filtered_results["Cluster"] == selected_cluster]
    if customer_search.strip():
        filtered_results = filtered_results.loc[
            filtered_results["CustomerID"].astype(str).str.contains(
                customer_search.strip(), regex=False
            )
        ]

    total_customers, cluster_count, average_spend = st.columns(3)
    total_customers.metric("Customers shown", f"{len(filtered_results):,}")
    cluster_count.metric("Clusters in dataset", f"{results['Cluster'].nunique():,}")
    average_spend.metric(
        "Average monetary value shown",
        f"{filtered_results['Monetary'].mean():,.2f}" if not filtered_results.empty else "—",
    )

    st.subheader("Customer ID, features, and assigned cluster")
    st.dataframe(
        filtered_results[REQUIRED_COLUMNS].sort_values("CustomerID"),
        width="stretch",
        height=520,
        hide_index=True,
        column_config={
            "CustomerID": st.column_config.NumberColumn("Customer ID", format="%d"),
            "RecencyDays": st.column_config.NumberColumn("Recency (days)", format="%.2f"),
            "Frequency": st.column_config.NumberColumn("Distinct invoices", format="%d"),
            "Monetary": st.column_config.NumberColumn("Monetary value", format="%.2f"),
            "Cluster": st.column_config.NumberColumn("Cluster", format="%d"),
        },
    )

    distribution, profiles = st.columns([1, 2])
    with distribution:
        st.subheader("Customers by cluster")
        cluster_counts = (
            results.groupby("Cluster", as_index=False)
            .agg(CustomerCount=("CustomerID", "size"))
            .sort_values("Cluster")
            .set_index("Cluster")
        )
        st.bar_chart(cluster_counts, y="CustomerCount", x_label="Cluster", y_label="Customers")

    with profiles:
        st.subheader("Cluster profiles")
        cluster_profiles = (
            results.groupby("Cluster")
            .agg(
                CustomerCount=("CustomerID", "size"),
                MedianRecencyDays=("RecencyDays", "median"),
                MedianFrequency=("Frequency", "median"),
                MedianMonetary=("Monetary", "median"),
            )
            .reset_index()
        )
        st.dataframe(
            cluster_profiles,
            width="stretch",
            hide_index=True,
            column_config={
                "Cluster": st.column_config.NumberColumn("Cluster", format="%d"),
                "CustomerCount": st.column_config.NumberColumn("Customers", format="%d"),
                "MedianRecencyDays": st.column_config.NumberColumn(
                    "Median recency (days)", format="%.2f"
                ),
                "MedianFrequency": st.column_config.NumberColumn(
                    "Median frequency (invoices)", format="%d"
                ),
                "MedianMonetary": st.column_config.NumberColumn(
                    "Median monetary value", format="%.2f"
                ),
            },
        )


if __name__ == "__main__":
    main()
